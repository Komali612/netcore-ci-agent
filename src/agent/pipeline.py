def _generic_name(prefix: str, label: str) -> str:
    return re.sub(r"[^A-Za-z0-9]+", "_", f"{prefix}_{label}").strip("_").upper()


def to_actions_secrets(selected_tools: dict) -> dict:
    """Flatten the UI's {capability: {tool, <label>: <value>}} into
    {ACTIONS_SECRET_NAME: value}. Masked placeholders and blanks are dropped, so
    only real values ever become secrets."""
    out: dict[str, str] = {}
    for capability, entry in (selected_tools or {}).items():
        if not isinstance(entry, dict):
            continue
        tool = entry.get("tool")
        for label, value in entry.items():
            if label == "tool" or value in (None, "", "[provided via UI]"):
                continue
            name = SECRET_MAP.get((tool, label)) or _generic_name(tool or capability, label)
            out[name] = value
    return out


# Orchestrator UI capability label -> the generator's internal capability key.
# (Metrics/APM and Log aggregation both feed the single "monitoring" step.)
CAP_BY_LABEL = {
    "Code coverage & quality": "coverage",
    "SAST (static analysis)": "sast",
    "SCA (dependency scan)": "sca",
    "DAST (dynamic scan)": "dast",
    "Container image scan": "imgscan",
    "Artifact repository": "artifact",
    "Container registry": "registry",
    "Metrics / APM": "monitoring",
    "Log aggregation": "monitoring",
}


def selected_caps(selected_tools: Optional[dict]) -> dict:
    """Translate the UI's ``{capability_label: {tool, ...}}`` into
    ``{internal_capability: tool_name}``. Capabilities the user left unselected
    are absent (the generator then comments their steps out). First tool wins
    when two labels map to the same capability (e.g. metrics before logs)."""
    caps: dict = {}
    for label, entry in (selected_tools or {}).items():
        cap = CAP_BY_LABEL.get(label)
        if not cap:
            continue
        tool = entry.get("tool") if isinstance(entry, dict) else None
        if tool:
            caps.setdefault(cap, tool)
    return caps


def _default_project_name(repo_url: str) -> str:
    tail = parse_repo_full_name(repo_url).split("/")[-1]
    cleaned = re.sub(r"[^A-Za-z0-9]+", " ", tail).title().replace(" ", "")
    return cleaned or "App"


def _pr_body(name: str, secret_results: list[dict]) -> str:
    set_names = [r["name"] for r in secret_results if r.get("status") == "set"]
    lines = [
        f"Automated CI pipeline for **{name}**, generated by NetcoreCIAgent.",
        "",
        "## What this adds",
        "- `.github/workflows/ci-pipeline.yml` — build, test, SonarQube, "
        "SAST/SCA/DAST, container build + SBOM + scan, Nexus, Helm, monitoring.",
        "",
        "## Secrets configured (values not shown)",
        (("- " + "\n- ".join(set_names)) if set_names else "- (none set this run)"),
        "",
        "> Review and merge when ready — this PR is **not** auto-merged.",
    ]
    return "\n".join(lines)


def run_ci_pipeline(
    *,
    repo_url: str,
    github_token: str,
    project_name: Optional[str] = None,
    options: Optional[dict] = None,
    pipeline_secrets: Optional[dict] = None,
    selected_tools: Optional[dict] = None,
    repo=None,
    discover_tool=None,
    generate_tool=None,
    validate_tool=None,
    secrets_provider: Optional[SecretsProvider] = None,
) -> dict:
    """Run the real CI flow. Returns a structured result incl. the live PR URL.

    Injectables (``repo``, ``*_tool``, ``secrets_provider``) let tests run the
    whole chain with mocks and no network.
    """
    options = options or {}

    # 1) Discover
    disc = (discover_tool or DiscoverProject()).run(
        repo_url=repo_url, branch=options.get("branch", "main")
    )
    if disc.get("status") == "error":
        return {"status": "error", "stage": "discover", "error": disc.get("error")}

    framework = disc.get("target_framework") or ".NET 8"
    name = project_name or _default_project_name(repo_url)

    # Sonar targeting: a real, repo-derived project key (SonarCloud's own
    # convention when binding a GitHub repo is "<owner>_<repo>"), and the org
    # from what the console collected — so the scan never ships __SONAR_*__.
    full_name = parse_repo_full_name(repo_url)
    sonar_project_key = options.get("sonar_project_key") or full_name.replace("/", "_")
    sonar_org = options.get("sonar_org") or (pipeline_secrets or {}).get("SONAR_ORG")

    # Runner comes from the orchestrator UI (free-text); blank -> ubuntu-latest.
    runner_os = (options.get("runner_os") or "").strip() or "ubuntu-latest"

    # Which optional CI tools the UI selected -> {capability: tool_name}. A
    # capability the user left "— not used —" is simply absent here, and the
    # generator emits its steps commented-out.
    enabled_tools = selected_caps(selected_tools)

    # 2) Generate
    gen = (generate_tool or GenerateGitHubActionsWorkflow()).run(
        project_name=name,
        target_framework=framework,
        build_tool=disc.get("build_tool") or ".NET CLI",
        runner_os=runner_os,
        enabled_tools=enabled_tools,
        project_files=disc.get("project_files") or [],
        solution_file=disc.get("solution_file"),
        sonar_project_key=sonar_project_key,
        sonar_org=sonar_org,
    )
    if gen.get("status") == "error":
        return {"status": "error", "stage": "generate", "error": gen.get("error")}
    workflow_yaml = gen["workflow_yaml"]
    workflow_path = gen["workflow_path"]

    # 3) Validate (fail fast rather than open a broken PR)
    val = (validate_tool or ValidateWorkflow()).run(
        workflow_yaml=workflow_yaml, workflow_name=f"{name}-ci"
    )
    if not val.get("valid"):
        return {"status": "validation_failed", "stage": "validate", "validation": val}

    # 4) Deliver secrets (Model A — GitHub Actions secrets)
    repo = repo or get_repo(github_token, parse_repo_full_name(repo_url))
    provider = secrets_provider or GitHubActionsSecrets(repo)
    secret_results = (
        provider.set_many(pipeline_secrets or {})
        if options.get("set_secrets", True)
        else []
    )

    # 5) Open a real PR (never merge)
    pr = None
    if options.get("open_pr", True):
        branch = options.get("pr_branch") or f"ci/netcore-{name.lower()}"
        pr = open_pr(
            repo,
            workflow_path=workflow_path,
            workflow_yaml=workflow_yaml,
            branch=branch,
            title=f"Add CI pipeline for {name}",
            body=_pr_body(name, secret_results),
        )

    # CI->CD handoff (ARCHITECTURE.md §2.1): the image this pipeline will publish.
    # The generated workflow's registry step pushes to GHCR as
    # ghcr.io/<owner>/<repo>:<commit-sha> (lowercased); the CD agent deploys exactly
    # that image, resolving the concrete tag at deploy time via its trigger.
    handoff = {
        "image_registry": "ghcr.io",
        "image_name": full_name.lower(),
        "image": f"ghcr.io/{full_name.lower()}",
        "image_tag_scheme": "${{ github.sha }}",
    }

    result = {
        "status": "opened" if pr else "generated",
        "repo": parse_repo_full_name(repo_url),
        "handoff": handoff,
        "discovery": {
            "target_framework": framework,
            "existing_ci_pipeline": disc.get("existing_ci_pipeline"),
        },
        "validation": {"valid": True},
        "secrets": secret_results,
        "workflow_path": workflow_path,
        "pr": pr,
    }
    failed = [r["name"] for r in secret_results if r.get("status") == "failed"]
    if failed:
        result["warnings"] = [
            "Could not set these Actions secrets: " + ", ".join(failed) +
            " — the GitHub token is missing the 'Secrets' (read/write) permission. "
            "The PR was still opened; add the permission (or set the secrets manually) "
            "and the pipeline will pick them up."
        ]
    return result

"""End-to-end CI pipeline authoring — the single entry point for a real run.

``run_ci_pipeline`` chains Discover -> Generate -> Validate -> deliver secrets
(via a ``SecretsProvider``) -> open a real PR. Dependencies are injectable so the
whole chain is unit-testable offline (mock repo, stub discover/generate). This is
the deterministic path the direct ``/ci`` endpoint calls — no LLM in the loop, so
real secret values are handled here, never sent to a model.
"""
from __future__ import annotations

import re
from typing import Optional

from .github_client import get_repo, open_pr, parse_repo_full_name
from .secrets_provider import GitHubActionsSecrets, SecretsProvider
from .tools.tools import (
    DiscoverProject,
    GenerateGitHubActionsWorkflow,
    ValidateWorkflow,
)

